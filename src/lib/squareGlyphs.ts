import type { Glyph, Stroke } from "../types";

function poly(...xy: number[]): Stroke {
  const pts: Stroke = [];
  for (let i = 0; i < xy.length; i += 2) {
    pts.push({ x: xy[i], y: xy[i + 1] });
  }
  return pts;
}

function g(width: number, ...strokes: Stroke[]): Glyph {
  return { width, strokes };
}

